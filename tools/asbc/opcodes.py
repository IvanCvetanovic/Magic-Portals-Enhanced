"""AngelScript bytecode instruction table, generated from the engine's own header.

Ported from ``asBCInfo[256]`` in
``reference/ethanon/toolkit/Source/src/angelscript/include/angelscript.h:1510``, and the
``asBCTypeSize[20]`` table above it at ``:1456``.

POINTER SIZE. Four instruction types are pointer-size dependent (``angelscript.h:1488-1502``):

    32-bit                          64-bit
    PTR_ARG    -> DW_ARG            -> QW_ARG
    PTR_DW_ARG -> DW_DW_ARG         -> QW_DW_ARG
    wW_PTR_ARG -> wW_DW_ARG         -> wW_QW_ARG
    rW_PTR_ARG -> rW_DW_ARG         -> rW_QW_ARG

The APK is an Android build and its pointer width is not recorded in the file, so it is a
parameter here rather than an assumption. The right value is the one that makes the whole
523,826-byte stream decode to a clean EOF — a length-prefixed format desynchronises
catastrophically within a few hundred bytes of a wrong guess, so this is a decisive test
rather than a preference.
"""

