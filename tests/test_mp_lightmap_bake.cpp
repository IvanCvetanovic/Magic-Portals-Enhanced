// The composition from the scene's data to the receiver and the lights the bake takes, and the whole of it against golden A:
// the pivot's sign, the rotation's sense and the owners' arithmetic go through the same functions the layer calls, and the
// bytes are the independent model's. FAILS UNDER: any sign slip between the Sprite2D offset and the origin, between the
// .tscn rotation and the esc angle, or in a light's height (owner z + offset z).
void TheComposedReceiverAndLightsBakeTheModelsBytes() {
    Sprites::Sprite sprite;
    sprite.node = "stone";
    sprite.texels = glm::ivec2(16, 16);
    sprite.density = 2.0f;
    sprite.scale = glm::dvec2(1.0);
    sprite.atPx = glm::dvec2(100.0, 50.0);
    sprite.rotation = -125.0 * kDegrees;
    sprite.offsetPx = glm::dvec2(0.0, 2.0);
    Lighting::Look look;
    look.z = 3.0;
    look.colour = glm::dvec4(1.0);

    const Receiver receiver = Lighting::BakeReceiver(sprite, look);
    CHECK_MSG(receiver.units == glm::ivec2(8, 8) && receiver.scale == glm::dvec2(1.0) &&
                  receiver.nodePx == glm::dvec2(100.0, 50.0) && receiver.offsetPx == glm::dvec2(0.0, 2.0) &&
                  receiver.turnRad == sprite.rotation && receiver.z == 3.0 && receiver.colour == glm::dvec3(1.0),
              "the sprite as the original sees the entity: units over the density, the offset as written, Godot's rotation");

    Lighting::Scene lighting;
    lighting.intensity = 4.5;
    lighting.nodes.emplace("lamp1", Owner(3.0, glm::dvec3(4.5, 9.0, 6.0), 14.0, glm::dvec3(1.0, 0.5, 0.25), true));
    lighting.nodes.emplace("walker", Owner(3.0, glm::dvec3(0.0, 0.0, 6.0), 14.0, glm::dvec3(1.0), false));
    lighting.nodes.emplace("lamp2", Owner(3.0, glm::dvec3(4.0, 7.0, 2.0), 12.0, glm::dvec3(0.9, 0.7, 0.5), true));
    const Tscn::Scene scene = SceneWithOwners();
    std::vector<SourceLight> lights;
    std::string error;
    CHECK_MSG(Lighting::BakeLights(scene, lighting, lights, error), error);
    CHECK_MSG(lights.size() == 2, "the static owners only, a moving light is the live pass's: " + std::to_string(lights.size()));
    if (lights.size() == 2) {
        CHECK_MSG(Near(lights[0].world, glm::dvec3(104.5, 49.0, 9.0), 1e-12) && lights[0].range == 14.0 &&
                      Near(lights[0].colour, glm::dvec3(4.5, 2.25, 1.125), 1e-12),
                  "owner position + offset, owner z + offset z, colour x the scene's intensity");
        CHECK_MSG(Near(lights[1].world, glm::dvec3(99.0, 52.0, 5.0), 1e-12) && lights[1].range == 12.0,
                  "and in the scene's file order");
    }
    const Baked baked = MustBake(Bits(5, 6, 5), receiver, DiffuseA(), nullptr, lights, "no map is flat");
    CHECK_MSG(baked.width == 8 && baked.height == 8, "a flat map is the same sprite");
    const Image normal = NormalA();
    const Baked golden = MustBake(Bits(5, 6, 5), receiver, DiffuseA(), &normal, lights, "golden A through the composition");
    CHECK_MSG(BytesApart(golden, kGoldenA565) == 0, "golden A from the scene's data: " + std::to_string(BytesApart(golden, kGoldenA565)) + " bytes apart");

    // A node that owns a light and has no position cannot be placed: said, not skipped.
    lighting.nodes.emplace("nowhere", Owner(0.0, glm::dvec3(0.0), 5.0, glm::dvec3(1.0), true));
    std::vector<SourceLight> none;
    CHECK_MSG(!Lighting::BakeLights(scene, lighting, none, error) && error.find("nowhere") != std::string::npos && none.empty(), error);
}

// ---- the light shader's term ----------------------------------------------------------------------------------------------
// spec.md vectors 1 and 2. FAILS UNDER: a green decode that is not 2n - 1 (vector 2's G reads 33 for 23), a renormalised
// normal, a factor of the diffuse alpha, a range test that is not strict.
void ThePassIsTheShadersTerm() {
    // Vector 1: white, the flat texel (128, 128, 255), a light at (1.5, 0.5, 4), range 8, colour (1, 0.5, 0.2) x 2, texel
    // (1.5, 0.5, 0): v = (0, 0, 4), facing 1, att = 1 - 16/64 = 0.75: (1.5, 0.75, 0.3) clamped to (1, 0.75, 0.3): levels
    // (31, 47, 9), bytes (255, 190, 74).
    const glm::dvec3 flat = glm::dvec3(128.0, 128.0, 255.0) / 255.0 * 2.0 - 1.0;
    PlacedLight one;
    one.at = glm::dvec3(1.5, 0.5, 4.0);
    one.range = 8.0;
    one.colour = glm::dvec3(2.0, 1.0, 0.4);
    glm::dvec3 pass = LightmapBake::Pass(one, glm::dvec3(1.5, 0.5, 0.0), flat, glm::dvec3(1.0));
    CHECK_MSG(Near(pass, glm::dvec3(1.0, 0.75, 0.3), 1e-12), "vector 1");
    CHECK(LightmapBake::LevelOf(pass.x, 31, LightmapBake::Rounding::Nearest) == 31);
    CHECK(LightmapBake::LevelOf(pass.y, 63, LightmapBake::Rounding::Nearest) == 47);
    CHECK(LightmapBake::LevelOf(pass.z, 31, LightmapBake::Rounding::Nearest) == 9);
    CHECK(LightmapBake::ByteOf(47, 63) == 190 && LightmapBake::ByteOf(9, 31) == 74 && LightmapBake::ByteOf(31, 31) == 255);

    // Vector 2: diffuse (204, 153, 128)/255, the texel (166, 64, 230) -> N = (0.301961, -0.498039, 0.803922) in the
    // original's y-DOWN frame (no flip), P = (1.5, 0.5, 0), L' = (5.5, 2.5, 6), range 12, colour (1, 0.5, 0.2) x 3: v = (4, 2, 6),
    // d2 = 56, att = 0.611111, facing = 0.672869: (0.986875, 0.370078, 0.123843), levels (31, 23, 4), bytes (255, 93, 33).
    PlacedLight two;
    two.at = glm::dvec3(5.5, 2.5, 6.0);
    two.range = 12.0;
    two.colour = glm::dvec3(3.0, 1.5, 0.6);
    const glm::dvec3 tilted = glm::dvec3(166.0, 64.0, 230.0) / 255.0 * 2.0 - 1.0;
    const glm::dvec3 tint = glm::dvec3(204.0, 153.0, 128.0) / 255.0;
    pass = LightmapBake::Pass(two, glm::dvec3(1.5, 0.5, 0.0), tilted, tint);
    CHECK_MSG(Near(pass, glm::dvec3(0.986875, 0.370078, 0.123843), 1e-6), std::to_string(pass.y));
    CHECK(LightmapBake::LevelOf(pass.x, 31, LightmapBake::Rounding::Nearest) == 31);
    CHECK(LightmapBake::LevelOf(pass.y, 63, LightmapBake::Rounding::Nearest) == 23);
    CHECK(LightmapBake::LevelOf(pass.z, 31, LightmapBake::Rounding::Nearest) == 4);
    CHECK(LightmapBake::ByteOf(23, 63) == 93 && LightmapBake::ByteOf(4, 31) == 33);
    // With the green sign wrong (+0.498039) the facing is 0.939083 and the levels (31, 33, 5): a test that sees it.
    glm::dvec3 greenUp = tilted;
    greenUp.y = -greenUp.y;
    const glm::dvec3 wrong = LightmapBake::Pass(two, glm::dvec3(1.5, 0.5, 0.0), greenUp, tint);
    CHECK_MSG(LightmapBake::LevelOf(wrong.y, 63, LightmapBake::Rounding::Nearest) == 33 &&
                  LightmapBake::LevelOf(wrong.z, 31, LightmapBake::Rounding::Nearest) == 5,
              "the other decode of the same texel reads 33 and 5, so the sign is pinned");
    // The normal is not renormalised: doubling its length doubles the pass (the Cg form would not).
    const glm::dvec3 half = LightmapBake::Pass(two, glm::dvec3(1.5, 0.5, 0.0), tilted * 0.5, tint);
    CHECK_MSG(Near(half, pass * 0.5, 1e-12), "the GLSL form: a short normal is a dim light");

    // Exactly zero at the range, and just inside it is not.
    PlacedLight edge;
    edge.at = glm::dvec3(0.0, 0.0, 5.0);
    edge.range = 5.0;
    edge.colour = glm::dvec3(1.0);
    CHECK_MSG(LightmapBake::Pass(edge, glm::dvec3(0.0), glm::dvec3(0.0, 0.0, 1.0), glm::dvec3(1.0)) == glm::dvec3(0.0), "d2 == r2 -> 0");
    edge.range = 5.001;
    CHECK(LightmapBake::Pass(edge, glm::dvec3(0.0), glm::dvec3(0.0, 0.0, 1.0), glm::dvec3(1.0)).x > 0.0);
    // Facing away adds nothing (negative clamps to 0).
    CHECK(LightmapBake::Pass(edge, glm::dvec3(0.0), glm::dvec3(0.0, 0.0, -1.0), glm::dvec3(1.0)) == glm::dvec3(0.0));
    // A light exactly on the point does not divide by zero.
    edge.at = glm::dvec3(0.0);
    const glm::dvec3 on = LightmapBake::Pass(edge, glm::dvec3(0.0), glm::dvec3(0.0, 0.0, 1.0), glm::dvec3(1.0));
    CHECK(std::isfinite(on.x) && std::isfinite(on.y) && std::isfinite(on.z));
}

// THE TWIN AS ORACLE: the engine's Light2D::Contribution is the original's shader in float (held to the Cg by the engine's
// own suite). Over a lattice of lights, points, normals and tints the module's double agrees with it to 1e-5. This is the
// first game-side use of Light2D::.
void ThePassAgreesWithTheEnginesTwin() {
    int cases = 0;
    double worst = 0.0;
    const std::array<glm::vec3, 3> texels{glm::vec3(128.0f, 128.0f, 255.0f) / 255.0f, glm::vec3(166.0f, 64.0f, 230.0f) / 255.0f,
                                          glm::vec3(30.0f, 220.0f, 140.0f) / 255.0f};
    const std::array<glm::vec3, 2> tints{glm::vec3(1.0f), glm::vec3(0.8f, 0.6f, 0.45f)};
    for (int lx = -2; lx <= 6; lx += 4) {
        for (int ly = -1; ly <= 7; ly += 4) {
            for (int lz = -3; lz <= 9; lz += 6) {
                for (const double range : {6.0, 14.0}) {
                    for (int px = 0; px < 8; px += 3) {
                        for (int py = 0; py < 8; py += 3) {
                            for (const glm::vec3& texel : texels) {
                                for (const glm::vec3& tint : tints) {
                                    PlacedLight light;
                                    light.at = glm::dvec3(lx, ly, lz);
                                    light.range = range;
                                    light.colour = glm::dvec3(2.0, 1.2, 0.7);
                                    const glm::dvec3 point(px + 0.5, py + 0.5, 0.0);
                                    const glm::dvec3 normal = glm::dvec3(texel) * 2.0 - 1.0;
                                    const glm::dvec3 mine = LightmapBake::Pass(light, point, normal, glm::dvec3(tint));
                                    Supersonic::GpuLight2D gpu;
                                    gpu.position = glm::vec3(light.at);
                                    gpu.range = static_cast<float>(range);
                                    gpu.color = glm::vec3(light.colour);
                                    gpu.layers = 1;
                                    const glm::vec3 theirs = Supersonic::Light2D::Contribution(
                                        gpu, 1, glm::vec3(point),
                                        Supersonic::Light2D::WorldNormal(texel, false, glm::mat4(1.0f)), tint);
                                    worst = std::max(worst, glm::length(mine - glm::dvec3(theirs)));
                                    ++cases;
                                }
                            }
                        }
                    }
                }
            }
        }
    }
    CHECK_MSG(cases > 1000, "a lattice of cases: " + std::to_string(cases));
    CHECK_MSG(worst < 1e-5, "the module against Light2D::Contribution, worst " + std::to_string(worst));
}

// ---- the store and the sum -----------------------------------------------------------------------------------------------
// FAILS UNDER: a store that is nearest where truncate is asked (or the reverse), a 5/6/5 grid of other bit counts, an
// expansion other than round(level * 255 / max).
void TheTargetsLevelsAndTheRoundingRule() {
    using LightmapBake::ByteOf;
    using LightmapBake::LevelOf;
    using LightmapBake::Rounding;
    CHECK(LevelOf(0.5, 3, Rounding::Nearest) == 2 && LevelOf(0.5, 3, Rounding::Truncate) == 1);   // 1.5 exactly
    CHECK(LevelOf(0.0, 31, Rounding::Nearest) == 0 && LevelOf(1.0, 31, Rounding::Nearest) == 31);
    CHECK_MSG(LevelOf(-0.25, 31, Rounding::Nearest) == 0 && LevelOf(1.75, 63, Rounding::Nearest) == 63 &&
                  LevelOf(1.75, 63, Rounding::Truncate) == 63,
              "the pass is clamped to [0, 1] before it is stored");
    CHECK(LevelOf(0.05, 31, Rounding::Nearest) == 2 && LevelOf(0.05, 31, Rounding::Truncate) == 1);   // 1.55
    CHECK(LevelOf(0.1, 31, Rounding::Nearest) == 3);                                                    // 3.1: one store of the sum
    // round(level * 255 / max).
    CHECK(ByteOf(0, 31) == 0 && ByteOf(1, 31) == 8 && ByteOf(31, 31) == 255 && ByteOf(16, 31) == 132);
    CHECK(ByteOf(0, 63) == 0 && ByteOf(1, 63) == 4 && ByteOf(32, 63) == 130 && ByteOf(63, 63) == 255);
    CHECK_MSG(ByteOf(128, 255) == 128 && ByteOf(255, 255) == 255 && ByteOf(77, 255) == 77, "an 8-bit channel expands to itself");
    // A ramp has exactly 32, 64 and 32 distinct bytes in the three channels of the 5/6/5 target.
    std::set<int> red;
    std::set<int> green;
    for (int i = 0; i <= 1000; ++i) {
        const double v = i / 1000.0;
        red.insert(ByteOf(LevelOf(v, 31, Rounding::Nearest), 31));
        green.insert(ByteOf(LevelOf(v, 63, Rounding::Nearest), 63));
    }
    CHECK_MSG(red.size() == 32 && green.size() == 64, std::to_string(red.size()) + " and " + std::to_string(green.size()));
}

// A sprite one unit square, white, flat, one light straight over its centre: the pass is the light's colour x 0.75.
Baked OneUnitUnder(const std::vector<SourceLight>& lights, const Rules& rules) {
    Receiver receiver;
    receiver.units = glm::ivec2(1, 1);
    receiver.nodePx = glm::dvec2(10.0, 10.0);
    return MustBake(rules, receiver, Solid(1, 1, 255, 255, 255), nullptr, lights, "one unit");
}

// ETHLightmapGen.cpp:86-168, spec.md 3.4 and vector 4: ONE store per light into a black temporary, and the lightmap is the
// saturating INTEGER sum of those levels. Two lights of 0.05 store 2 levels each and sum to 4 (a single store of the sum
// 0.1 would give 3); two of 20 levels in a 5-bit channel sum to 40 and saturate at 31, and in a 6-bit channel stay 40.
// FAILS UNDER: one store of the summed pass (byte 25 for 33), a sum that wraps or is not clamped, a clamp that is not per
// light.
void TheStoreIsOncePerLightAndTheSumSaturates() {
    // Light straight above the centre (10.5 - 0.5 = O: the node's frame is O = (0.5, 0.5), so world = (10, 10)), height 2,
    // range 4: att = 1 - 4/16 = 0.75, facing 1.
    const auto above = [](const glm::dvec3& colour) { return SourceLight{glm::dvec3(10.0, 10.0, 2.0), 4.0, colour}; };
    const double small = 0.05 / 0.75;
    const std::vector<SourceLight> two{above(glm::dvec3(small, 0.0, 0.0)), above(glm::dvec3(small, 0.0, 0.0))};
    Baked baked = OneUnitUnder(two, Bits(5, 6, 5));
    CHECK_MSG(Texel(baked, 0, 0)[0] == LightmapBake::ByteOf(4, 31), "two stores of 2 levels sum to level 4: byte " + std::to_string(Texel(baked, 0, 0)[0]));
    baked = OneUnitUnder({above(glm::dvec3(2.0 * small, 0.0, 0.0))}, Bits(5, 6, 5));
    CHECK_MSG(Texel(baked, 0, 0)[0] == LightmapBake::ByteOf(3, 31), "one store of the sum is level 3: a different lightmap");

    // 20/31 and 20/63 of a pass, twice: levels 20 + 20 = 40 -> R 31, G 40, B 31 (vector 4): bytes (255, 162, 255).
    const std::vector<SourceLight> full{above(glm::dvec3(20.0 / 31.0 / 0.75, 20.0 / 63.0 / 0.75, 20.0 / 31.0 / 0.75)),
                                        above(glm::dvec3(20.0 / 31.0 / 0.75, 20.0 / 63.0 / 0.75, 20.0 / 31.0 / 0.75))};
    baked = OneUnitUnder(full, Bits(5, 6, 5));
    CHECK_MSG(Texel(baked, 0, 0) == (std::array<int, 3>{255, 162, 255}),
              "(31, 40, 31) levels: " + std::to_string(Texel(baked, 0, 0)[0]) + " " + std::to_string(Texel(baked, 0, 0)[1]) + " " + std::to_string(Texel(baked, 0, 0)[2]));
    // Each pass is clamped to [0, 1] on its own before it is stored: 1.5 + 1.5 is 31 + 31 -> 31, and a pass of 3 does not
    // beat two of 1.5 by a level.
    const std::vector<SourceLight> bright{above(glm::dvec3(2.0)), above(glm::dvec3(2.0))};
    baked = OneUnitUnder(bright, Bits(5, 6, 5));
    CHECK(Texel(baked, 0, 0) == (std::array<int, 3>{255, 255, 255}));
    // The order of the lights changes nothing: an integer sum is commutative.
    std::vector<SourceLight> reversed = full;
    std::reverse(reversed.begin(), reversed.end());
    const Baked back = OneUnitUnder(reversed, Bits(5, 6, 5));
    CHECK_MSG(back.rgba == OneUnitUnder(full, Bits(5, 6, 5)).rgba, "the same lightmap in the other order");
    // No light: black, opaque.
    baked = OneUnitUnder({}, Bits(5, 6, 5));
    CHECK(Texel(baked, 0, 0) == (std::array<int, 3>{0, 0, 0}) && baked.rgba[3] == 255);
}

// ---- where a texel is read --------------------------------------------------------------------------------------------------
// The design's closed forms: a 4 x 4 sprite, flat normal, white, one light at (2, 2, 2) of range 4 over its centre: texel (1, 1),
// centre (1.5, 1.5, 0): v = (0.5, 0.5, 2), d2 = 4.5, att = 0.71875, facing = 2/sqrt(4.5): 0.67764 -> levels (21, 43, 21) ->
// bytes (173, 174, 173); texel (0, 0): 0.32156 -> (10, 20, 10) -> (82, 81, 82); and by the light's symmetry (3, 3) = (0, 0).
// FAILS UNDER: texel centres on the integer lattice (the half-unit shift that costs the judged levels 1.48 -> 2.28), a y flip.
void ATexelIsReadAtItsCentre() {
    Receiver receiver;
    receiver.units = glm::ivec2(4, 4);
    receiver.nodePx = glm::dvec2(10.0, 10.0);
    const std::vector<SourceLight> light{SourceLight{glm::dvec3(10.0, 10.0, 2.0), 4.0, glm::dvec3(1.0)}};
    const Baked baked = MustBake(Bits(5, 6, 5), receiver, Solid(1, 1, 255, 255, 255), nullptr, light, "4x4");
    CHECK(baked.width == 4 && baked.height == 4);
    CHECK_MSG(Texel(baked, 1, 1) == (std::array<int, 3>{173, 174, 173}), std::to_string(Texel(baked, 1, 1)[0]));
    CHECK_MSG(Texel(baked, 0, 0) == (std::array<int, 3>{82, 81, 82}), std::to_string(Texel(baked, 0, 0)[0]));
    CHECK(Texel(baked, 3, 3) == Texel(baked, 0, 0) && Texel(baked, 0, 3) == Texel(baked, 0, 0) && Texel(baked, 3, 0) == Texel(baked, 0, 0));
    CHECK(Texel(baked, 2, 2) == Texel(baked, 1, 1) && Texel(baked, 1, 2) == Texel(baked, 1, 1));

    // The anchor: a 5 x 3 sprite with a light at (2.5, 1.5, 1) is straight over texel (2, 1)'s centre. In an 8-bit target
    // that texel is the unique maximum, and the texels either side of it, above and below it, are equal pairs.
    Receiver wide;
    wide.units = glm::ivec2(5, 3);
    wide.nodePx = glm::dvec2(20.0, 20.0);
    const std::vector<SourceLight> over{SourceLight{glm::dvec3(20.0, 20.0, 1.0), 3.0, glm::dvec3(1.0)}};
    const Baked lit = MustBake(Bits(8, 8, 8), wide, Solid(1, 1, 255, 255, 255), nullptr, over, "5x3");
    int maxima = 0;
    for (int y = 0; y < 3; ++y) {
        for (int x = 0; x < 5; ++x) {
            if (Texel(lit, x, y)[0] >= Texel(lit, 2, 1)[0] && !(x == 2 && y == 1)) ++maxima;
        }
    }
    CHECK_MSG(maxima == 0, "(2, 1) is the unique brightest texel");
    CHECK(Texel(lit, 1, 1) == Texel(lit, 3, 1) && Texel(lit, 2, 0) == Texel(lit, 2, 2) && Texel(lit, 0, 0) == Texel(lit, 4, 2));
    CHECK_MSG(Texel(lit, 2, 1)[0] == 227, "0.8889 of 255 = 226.67 -> 227: " + std::to_string(Texel(lit, 2, 1)[0]));
}

// ONE bilinear tap of each map at the texel's centre, clamped (spec.md 2.3, vector 5). Expected values are the tint and
// the normal worked by hand, put through the same Pass the shader's term is pinned by above. FAILS UNDER: a box filter
// (a 4-to-1 diffuse reads the middle two texels, not the four), a nearest tap, a wrap at the edge, and a normal map read
// at the wrong magnification.
void TheMapsAreTappedBilinearlyAtTheTexelCentre() {
    const Rules rules = Bits(8, 8, 8);
    const auto expectedByte = [&](const PlacedLight& light, int column, int row, const glm::dvec3& tint, const glm::dvec3& normalEncoded) {
        const glm::dvec3 pass = LightmapBake::Pass(light, glm::dvec3(column + 0.5, row + 0.5, 0.0), normalEncoded * 2.0 - 1.0, tint);
        return std::array<int, 3>{LightmapBake::LevelOf(pass.x, 255, LightmapBake::Rounding::Nearest),
                                  LightmapBake::LevelOf(pass.y, 255, LightmapBake::Rounding::Nearest),
                                  LightmapBake::LevelOf(pass.z, 255, LightmapBake::Rounding::Nearest)};
    };
    Receiver receiver;
    receiver.units = glm::ivec2(2, 1);
    receiver.nodePx = glm::dvec2(10.0, 10.0);
    // O = (1, 0.5); the light at node + (0, 0) is over the middle, 3 high: texels 0 and 1 are mirror images.
    const SourceLight source{glm::dvec3(10.0, 10.0, 3.0), 12.0, glm::dvec3(0.6)};
    const PlacedLight light = LightmapBake::PlaceLight(receiver, source);
    const glm::dvec3 flat(0.5, 0.5, 1.0);

    // 4 texels a unit (a 4:1 diffuse): texel k reads columns 4k + 1 and 4k + 2 (weights 1/2 each), NOT the four of its block.
    Image four = Solid(8, 4, 0, 0, 0);
    for (int y = 0; y < 4; ++y) {
        for (int x = 0; x < 8; ++x) {
            const std::uint8_t v = (x % 4 == 0 || x % 4 == 3) ? 200 : 40;
            Put(four, x, y, v, v, v, 255);
        }
    }
    Baked baked = MustBake(rules, receiver, four, nullptr, {source}, "4:1");
    for (int k = 0; k < 2; ++k) {
        const std::array<int, 3> want = expectedByte(light, k, 0, glm::dvec3(40.0 / 255.0), flat);
        CHECK_MSG(Texel(baked, k, 0) == want, "4:1 texel " + std::to_string(k) + ": " + std::to_string(Texel(baked, k, 0)[0]) + " against " + std::to_string(want[0]));
    }
    // 2 texels a unit (the hd art): the exact mean of the 2 x 2 block.
    Image two = Solid(4, 2, 0, 0, 0);
    const std::uint8_t row[4] = {200, 40, 100, 220};
    for (int y = 0; y < 2; ++y) {
        for (int x = 0; x < 4; ++x) Put(two, x, y, row[x], row[x], row[x], 255);
    }
    baked = MustBake(rules, receiver, two, nullptr, {source}, "2:1");
    CHECK(Texel(baked, 0, 0) == expectedByte(light, 0, 0, glm::dvec3(120.0 / 255.0), flat));
    CHECK(Texel(baked, 1, 0) == expectedByte(light, 1, 0, glm::dvec3(160.0 / 255.0), flat));
    // 1:1: the texel itself, exactly.
    Receiver four1 = receiver;
    four1.units = glm::ivec2(4, 1);
    const PlacedLight light4 = LightmapBake::PlaceLight(four1, source);
    Image one = Solid(4, 1, 0, 0, 0);
    const std::uint8_t exact[4] = {30, 90, 150, 250};
    for (int x = 0; x < 4; ++x) Put(one, x, 0, exact[x], exact[x], exact[x], 255);
    baked = MustBake(rules, four1, one, nullptr, {source}, "1:1");
    for (int k = 0; k < 4; ++k) {
        CHECK_MSG(Texel(baked, k, 0) == expectedByte(light4, k, 0, glm::dvec3(exact[k] / 255.0), flat), "1:1 texel " + std::to_string(k));
    }
    // A half-resolution normal map: 2 texels over 4 units read [a, .75a + .25b, .25a + .75b, b], the ends clamped (vector 5).
    const std::uint8_t a[3] = {60, 200, 255};
    const std::uint8_t b[3] = {220, 90, 255};
    Image normal = Solid(2, 1, 0, 0, 0);
    Put(normal, 0, 0, a[0], a[1], a[2], 255);
    Put(normal, 1, 0, b[0], b[1], b[2], 255);
    baked = MustBake(rules, four1, Solid(4, 1, 255, 255, 255), &normal, {source}, "half-resolution normal");
    const double weight[4] = {1.0, 0.75, 0.25, 0.0};   // of a
    for (int k = 0; k < 4; ++k) {
        glm::dvec3 mixed;
        for (glm::length_t c = 0; c < 3; ++c) mixed[c] = (weight[k] * a[c] + (1.0 - weight[k]) * b[c]) / 255.0;
        CHECK_MSG(Texel(baked, k, 0) == expectedByte(light4, k, 0, glm::dvec3(1.0), mixed), "normal texel " + std::to_string(k));
    }
    // The instance colour multiplies the pass.
    Receiver tinted = four1;
    tinted.colour = glm::dvec3(0.5, 1.0, 0.25);
    baked = MustBake(rules, tinted, Solid(4, 1, 255, 255, 255), nullptr, {source}, "tinted");
    for (int k = 0; k < 4; ++k) {
        CHECK_MSG(Texel(baked, k, 0) == expectedByte(light4, k, 0, glm::dvec3(0.5, 1.0, 0.25), flat), "tinted texel " + std::to_string(k));
    }
    // An alpha-0 texel adds nothing and drags its neighbours' tap down with it (it loads as black).
    Image hole = Solid(4, 1, 255, 255, 255);
    Put(hole, 1, 0, 255, 255, 255, 0);
    baked = MustBake(rules, four1, hole, nullptr, {source}, "hole");
    CHECK(Texel(baked, 1, 0) == (std::array<int, 3>{0, 0, 0}));
    CHECK(Texel(baked, 0, 0) == expectedByte(light4, 0, 0, glm::dvec3(1.0), flat));
}

// ---- the whole bake against the independent model -------------------------------------------------------------------------
// The bytes calibrator A's model gives for the same synthetic input. FAILS UNDER: the rotation's sense, the pivot's sign, the
// mask or the stretch left out, the normal map's sampling, a nearest store where the model's is nearest-by-light, a sum
// that is not per light, the half-unit anchor.
void TheBakeAgreesWithTheIndependentModelByteForByte() {
    const Image normalA = NormalA();
    const Image normalB = NormalB();
    {
        const Baked baked = MustBake(Bits(5, 6, 5), ReceiverA(), DiffuseA(), &normalA, LightsA(), "A 5/6/5");
        CHECK_MSG(baked.width == 8 && baked.height == 8, "A is 8 x 8 texels at one unit a texel");
        CHECK_MSG(BytesApart(baked, kGoldenA565) == 0, "A, 5/6/5, nearest: " + std::to_string(BytesApart(baked, kGoldenA565)) + " bytes apart");
    }
    {
        const Baked baked = MustBake(Bits(5, 6, 5, LightmapBake::Rounding::Truncate), ReceiverA(), DiffuseA(), &normalA, LightsA(), "A truncate");
        CHECK_MSG(BytesApart(baked, kGoldenA565Truncated) == 0, "A, 5/6/5, truncating: " + std::to_string(BytesApart(baked, kGoldenA565Truncated)) + " bytes apart");
    }
    {
        const Baked baked = MustBake(Bits(8, 8, 8), ReceiverA(), DiffuseA(), &normalA, LightsA(), "A 8/8/8");
        CHECK_MSG(BytesApart(baked, kGoldenA888) == 0, "A, 8/8/8: " + std::to_string(BytesApart(baked, kGoldenA888)) + " bytes apart");
    }
    {
        // B: its maps are not powers of two on either axis (3 x 3 diffuse, 4 x 3 normal), so the stretch is on the path.
        const Baked baked = MustBake(Bits(5, 6, 5), ReceiverB(), DiffuseB(), &normalB, LightsB(), "B");
        CHECK_MSG(baked.width == 6 && baked.height == 6, "B is 6 x 6");
        CHECK_MSG(BytesApart(baked, kGoldenB565) == 0, "B, stretched maps: " + std::to_string(BytesApart(baked, kGoldenB565)) + " bytes apart");
    }
    {
        // The mask and the stretch are each on the path: without the mask the alpha-0 and key texels would light the sprite.
        Image unmasked = DiffuseA();
        Put(unmasked, 3, 5, 200, 100, 50, 255);
        Put(unmasked, 7, 2, 254, 0, 255, 255);
        const Baked baked = MustBake(Bits(5, 6, 5), ReceiverA(), unmasked, &normalA, LightsA(), "A without its holes");
        CHECK_MSG(BytesApart(baked, kGoldenA565) > 0, "the holes in the art are holes in the light");
    }
}

// ---- the shipped pitch -----------------------------------------------------------------------------------------------------
// The judge's V8 (calibration.md): [0, 0, 0, 0, 255, 0, 0, 0] -> [-2.988, 28.887, 110.566, -8.965] -> rounded and clamped
// [0, 29, 111, 0]; a constant stays constant, edges included; the 12-texel ramp 10j + 5 reads [9.4922, 29.8828, 50, 70, 90.1172,
// 110.5078] (exact in the interior, the mirror edge bends the first and last). FAILS UNDER: taps that are not the Keys a = -0.5
// kernel, a clamped or renormalised edge, rows and columns in the wrong sizes.
void TheShippedPitchIsTheUnitBakeReducedByTheFixedTaps() {
    Rules rules;
    const auto reduce = [&](const std::vector<std::uint8_t>& plane, int width, int height) {
        std::vector<std::uint8_t> rgb;
        for (const std::uint8_t v : plane) rgb.insert(rgb.end(), {v, v, v});
        return LightmapBake::Reduce(rules.reduction, rgb, width, height);
    };
    std::vector<std::uint8_t> spike(16, 0);
    for (int y = 0; y < 2; ++y) spike[static_cast<std::size_t>(y * 8 + 4)] = 255;
    std::vector<std::uint8_t> out = reduce(spike, 8, 2);
    CHECK_MSG(out.size() == 4 * 3, "8 x 2 reduces to 4 x 1");
    if (out.size() == 12) {
        CHECK_MSG(out[0] == 0 && out[3] == 29 && out[6] == 111 && out[9] == 0, "V8: " + std::to_string(out[3]) + " " + std::to_string(out[6]));
        CHECK(out[4] == out[3] && out[5] == out[3] && out[10] == out[9]);
    }
    CHECK_MSG(reduce(std::vector<std::uint8_t>(8 * 4, 255), 8, 4) == std::vector<std::uint8_t>(4 * 2 * 3, 255), "a constant 255 stays 255 at every edge");
    CHECK(reduce(std::vector<std::uint8_t>(6 * 2, 77), 6, 2) == std::vector<std::uint8_t>(3 * 1 * 3, 77));
    std::vector<std::uint8_t> ramp;
    for (int y = 0; y < 2; ++y) {
        for (int j = 0; j < 12; ++j) ramp.push_back(static_cast<std::uint8_t>(10 * j + 5));
    }
    out = reduce(ramp, 12, 2);
    const int want[6] = {9, 30, 50, 70, 90, 111};
    for (int k = 0; k < 6 && out.size() == 18; ++k) CHECK_MSG(out[static_cast<std::size_t>(k) * 3] == want[k], "ramp " + std::to_string(k));
    // A size it cannot reduce comes back empty, not wrong.
    CHECK(reduce(std::vector<std::uint8_t>(5 * 2, 1), 5, 2).empty());

    // The whole bake at pitch 2: the 8/8/8 unit bake of A, reduced (the exact arithmetic of gen_golden.py).
    const Image normalA = NormalA();
    const Baked baked = MustBake(Bits(8, 8, 8, LightmapBake::Rounding::Nearest, 2), ReceiverA(), DiffuseA(), &normalA, LightsA(), "A pitch 2");
    CHECK_MSG(baked.width == 4 && baked.height == 4, "half the texels a side");
    CHECK_MSG(BytesApart(baked, kGoldenA888P2) == 0, "A, pitch 2: " + std::to_string(BytesApart(baked, kGoldenA888P2)) + " bytes apart");
}

// ---- determinism and refusals -----------------------------------------------------------------------------------------------
void ABakeIsTheSameBytesEveryTime() {
    const Image normalA = NormalA();
    const Rules rules = Bits(5, 6, 5);
    const Baked first = MustBake(rules, ReceiverA(), DiffuseA(), &normalA, LightsA(), "first");
    const Baked second = MustBake(rules, ReceiverA(), DiffuseA(), &normalA, LightsA(), "second");
    CHECK_MSG(first.rgba == second.rgba && first.width == second.width, "two bakes of the same input are byte-equal");
    std::vector<SourceLight> reversed = LightsA();
    std::reverse(reversed.begin(), reversed.end());
    const Baked back = MustBake(rules, ReceiverA(), DiffuseA(), &normalA, reversed, "reversed");
    CHECK_MSG(first.rgba == back.rgba, "the order of the lights does not matter");
    const Image copy = DiffuseA();
    CHECK_MSG(copy.rgba == DiffuseA().rgba, "the source is copied, never written to");
}

void ASpriteItCannotBakeIsRefusedByName() {
    const Rules rules = Bits(5, 6, 5);
    Baked baked;
    std::string error;
    const Image white = Solid(2, 2, 255, 255, 255);
    Receiver receiver;
    receiver.units = glm::ivec2(0, 8);
    CHECK_MSG(!LightmapBake::Bake(rules, receiver, white, nullptr, {}, baked, error) && error.find("0x8") != std::string::npos && baked.rgba.empty(), error);
    receiver.units = glm::ivec2(7, 8);
    Rules pitched = rules;
    pitched.unitsPerTexel = 2;
    CHECK_MSG(!LightmapBake::Bake(pitched, receiver, white, nullptr, {}, baked, error) && error.find("7x8") != std::string::npos, error);
    pitched.unitsPerTexel = 3;
    receiver.units = glm::ivec2(6, 6);
    CHECK_MSG(!LightmapBake::Bake(pitched, receiver, white, nullptr, {}, baked, error) && error.find("3") != std::string::npos, error);
    Image broken = white;
    broken.rgba.pop_back();
    CHECK_MSG(!LightmapBake::Bake(rules, receiver, broken, nullptr, {}, baked, error) && error.find("length") != std::string::npos, error);
    CHECK_MSG(!LightmapBake::Bake(rules, receiver, white, &broken, {}, baked, error), "a broken normal map is refused as well");
    receiver.scale = glm::dvec2(0.0, 1.0);
    CHECK_MSG(!LightmapBake::Bake(rules, receiver, white, nullptr, {}, baked, error) && error.find("scale") != std::string::npos, error);
}

