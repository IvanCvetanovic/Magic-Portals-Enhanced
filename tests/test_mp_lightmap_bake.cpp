// ---- the rules -----------------------------------------------------------------------------------------------------
bool ParseBlock(const std::string& text, Rules& rules, std::string& error) {
    Supersonic::Json::Parser parser(text);
    Supersonic::Json::Value root;
    if (!parser.Parse(root)) {
        error = parser.Error();
        return false;
    }
    return LightmapBake::ParseRules(root, rules, error);
}

std::string BlockWith(const std::string& pitch, const std::string& bits, const std::string& rounding, const std::string& reduction) {
    return "{\"units_per_texel\": {\"value\": " + pitch + "}, \"target\": {" + bits + ", \"rounding\": " + rounding +
           "}, \"reduction\": " + reduction + "}";
}

