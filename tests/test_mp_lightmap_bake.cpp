Image Solid(int width, int height, std::uint8_t r, std::uint8_t g, std::uint8_t b, std::uint8_t a = 255) {
    Image image;
    image.width = width;
    image.height = height;
    for (int i = 0; i < width * height; ++i) {
        image.rgba.insert(image.rgba.end(), {r, g, b, a});
    }
    return image;
}

void Put(Image& image, int x, int y, std::uint8_t r, std::uint8_t g, std::uint8_t b, std::uint8_t a) {
    const std::size_t at = (static_cast<std::size_t>(y) * static_cast<std::size_t>(image.width) + static_cast<std::size_t>(x)) * 4u;
    image.rgba[at + 0] = r;
    image.rgba[at + 1] = g;
    image.rgba[at + 2] = b;
    image.rgba[at + 3] = a;
}

std::array<std::uint8_t, 4> Get(const Image& image, int x, int y) {
    const std::size_t at = (static_cast<std::size_t>(y) * static_cast<std::size_t>(image.width) + static_cast<std::size_t>(x)) * 4u;
    return {image.rgba[at], image.rgba[at + 1], image.rgba[at + 2], image.rgba[at + 3]};
}

std::uint8_t Byte(int value) {
    return static_cast<std::uint8_t>(value);
}

