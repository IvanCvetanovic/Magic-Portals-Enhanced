// The rgb of a baked texel.
std::array<int, 3> Texel(const Baked& baked, int x, int y) {
    const std::size_t at = (static_cast<std::size_t>(y) * static_cast<std::size_t>(baked.width) + static_cast<std::size_t>(x)) * 4u;
    return {baked.rgba[at], baked.rgba[at + 1], baked.rgba[at + 2]};
}

// How many bytes of `baked` (rgb) differ from a golden (rgb triples), and whether alpha is opaque throughout.
template <std::size_t N>
int BytesApart(const Baked& baked, const std::uint8_t (&golden)[N]) {
    if (baked.rgba.size() * 3u != N * 4u) return static_cast<int>(N);
    int apart = 0;
    for (std::size_t texel = 0; texel * 4u < baked.rgba.size(); ++texel) {
        for (std::size_t c = 0; c < 3; ++c) {
            if (baked.rgba[texel * 4u + c] != golden[texel * 3u + c]) ++apart;
        }
        if (baked.rgba[texel * 4u + 3] != 255) ++apart;
    }
    return apart;
}

bool Near(const glm::dvec3& a, const glm::dvec3& b, double eps) {
    return std::abs(a.x - b.x) <= eps && std::abs(a.y - b.y) <= eps && std::abs(a.z - b.z) <= eps;
}

